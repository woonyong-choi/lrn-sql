#!/usr/bin/env python3
"""새 엔진·SQLite·PostgreSQL에 같은 SQL을 실행해 결과를 비교한다(3자 차분). 합성 데이터만 쓴다.

판정(사례의 질의마다):
  - 세 엔진이 같은 행을 내면 PASS. ORDER BY가 없으면 행 순서는 보지 않는다.
  - 기대가 error인 질의는 세 엔진 모두 오류여야 PASS다(오류 문구는 보지 않는다).
  - differs가 있는 질의는 우리 엔진이 정해진 쪽(sqlite 또는 postgres)과 같아야 PASS이며 차이 이유를 남긴다.
  - PostgreSQL에 닿지 못하면 그 엔진은 NOT-RUN으로 표시하고 나머지 둘을 비교한다(--require-postgres면 실패).

DDL은 PostgreSQL에서만 형식 이름을 바꾼다: INTEGER→BIGINT(우리 정수는 64비트), REAL→DOUBLE PRECISION,
BLOB→BYTEA, INTEGER PRIMARY KEY AUTOINCREMENT→BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY.

사용법:
  TOTEDB_LIB=build/lib/libtotedb.so PYTHONPATH=python python3 tests/sql_diff.py \\
      [--dsn postgresql://diff:diff@localhost:5432/sqldiff] [--require-postgres] [--only 이름]
"""

from __future__ import annotations

import argparse
import math
import os
import re
import secrets
import sqlite3
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sql_diff_cases import CASES  # noqa: E402

Row = tuple[Any, ...]


class EngineError(Exception):
    """엔진이 문장을 오류로 거절했다."""


def normalize(value: Any) -> Any:
    if value is None:
        return None
    if isinstance(value, bool):
        return ("num", float(value))
    if isinstance(value, int | float):
        return ("num", float(value))
    if hasattr(value, "is_finite"):  # Decimal
        return ("num", float(value))
    if isinstance(value, memoryview | bytearray):
        return ("bytes", bytes(value))
    if isinstance(value, bytes):
        return ("bytes", value)
    return ("text", str(value))


def same_cell(a: Any, b: Any) -> bool:
    if a is None or b is None:
        return a is b
    if a[0] != b[0]:
        return False
    if a[0] == "num":
        return a[1] == b[1] or math.isclose(a[1], b[1], rel_tol=1e-12, abs_tol=1e-300)
    return a[1] == b[1]


def same_rows(a: list[Row], b: list[Row], ordered: bool) -> bool:
    if len(a) != len(b):
        return False
    if not ordered:
        a = sorted(a, key=repr)
        b = sorted(b, key=repr)
    return all(len(x) == len(y) and all(same_cell(p, q) for p, q in zip(x, y, strict=True)) for x, y in zip(a, b, strict=True))


class Lrn:
    name = "ours"

    def __init__(self, directory: Path) -> None:
        from totedb import Database  # noqa: PLC0415

        self.db = Database(directory / f"{secrets.token_hex(4)}.lrdb", busy_timeout_s=5.0)

    def run(self, sql: str) -> list[Row] | None:
        try:
            result = self.db.execute(sql)
        except Exception as err:  # noqa: BLE001 - 엔진 오류는 모두 같은 판정이다
            if type(err).__name__ in {"InvalidArgumentError"}:
                raise
            raise EngineError(str(err)) from err
        if result.columns:
            return [tuple(normalize(v) for v in row) for row in result.rows]
        return None

    def close(self) -> None:
        self.db.close()


class Sqlite:
    name = "sqlite"

    def __init__(self) -> None:
        self.conn = sqlite3.connect(":memory:", isolation_level=None)

    def run(self, sql: str) -> list[Row] | None:
        try:
            cursor = self.conn.execute(sql)
        except sqlite3.Error as err:
            raise EngineError(str(err)) from err
        if cursor.description is None:
            return None
        return [tuple(normalize(v) for v in row) for row in cursor.fetchall()]

    def close(self) -> None:
        self.conn.close()


PG_TYPES = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bREAL\b", re.I), "DOUBLE PRECISION"),
    (re.compile(r"\bBLOB\b", re.I), "BYTEA"),
]


def pg_sql(sql: str) -> str:
    if re.match(r"\s*CREATE\s+TABLE", sql, re.I):
        for pattern, replacement in PG_TYPES:
            sql = pattern.sub(replacement, sql)
    # CAST(x AS INTEGER|REAL|BLOB)도 같은 형식으로 맞춘다
    sql = re.sub(r"\bAS\s+INTEGER\b", "AS BIGINT", sql, flags=re.I)
    sql = re.sub(r"\bAS\s+REAL\b", "AS DOUBLE PRECISION", sql, flags=re.I)
    return re.sub(r"\bAS\s+BLOB\b", "AS BYTEA", sql, flags=re.I)


class Postgres:
    name = "postgres"

    def __init__(self, dsn: str) -> None:
        import psycopg  # noqa: PLC0415

        self.conn = psycopg.connect(dsn, autocommit=True)
        self.schema = f"d_{secrets.token_hex(6)}"
        self.conn.execute(f"CREATE SCHEMA {self.schema}")
        self.conn.execute(f"SET search_path TO {self.schema}")

    def run(self, sql: str) -> list[Row] | None:
        import psycopg  # noqa: PLC0415

        try:
            cursor = self.conn.execute(pg_sql(sql))
        except psycopg.Error as err:
            raise EngineError(str(err).splitlines()[0]) from err
        if cursor.description is None:
            return None
        return [tuple(normalize(v) for v in row) for row in cursor.fetchall()]

    def close(self) -> None:
        self.conn.execute(f"DROP SCHEMA {self.schema} CASCADE")
        self.conn.close()


@dataclass
class Verdict:
    case: str
    sql: str
    outcome: str
    detail: str = ""


def outcome_of(engine: Any, sql: str) -> tuple[str, Any]:
    try:
        return "rows", engine.run(sql)
    except EngineError as err:
        return "error", str(err)


def judge(query: dict[str, Any], results: dict[str, tuple[str, Any]]) -> tuple[str, str]:
    sql = query["sql"]
    ordered = bool(re.search(r"\bORDER\s+BY\b", sql, re.I))
    ours = results["ours"]
    others = {k: v for k, v in results.items() if k != "ours" and v is not None}
    if query.get("error"):
        bad = [k for k, v in results.items() if v is not None and v[0] != "error"]
        return ("PASS", "") if not bad else ("FAIL", f"오류를 기대했지만 성공: {bad}")
    differs = query.get("differs")
    if differs and differs["like"] not in others:
        return "NOT-RUN", f"기준 엔진 {differs['like']} 없음"
    targets = {differs["like"]: others[differs["like"]]} if differs else others
    for name, other in targets.items():
        if ours[0] == "error" or other[0] == "error":
            if ours[0] != other[0]:
                return "FAIL", f"{name}: ours={ours[0]}:{str(ours[1])[:80]} {name}={other[0]}:{str(other[1])[:80]}"
            continue
        if not same_rows(ours[1] or [], other[1] or [], ordered):
            return "FAIL", f"{name}: ours={ours[1]} {name}={other[1]}"
    if differs:
        return "DIFF", differs["reason"]
    return "PASS", ""


def run_case(case: dict[str, Any], workdir: Path, dsn: str | None, *, require_postgres: bool) -> list[Verdict]:
    pg_note = ""
    postgres = None
    if dsn:
        try:
            postgres = Postgres(dsn)
        except Exception as err:  # noqa: BLE001 - 연결 실패의 종류와 상관없이 같은 판정이다
            pg_note = f"postgres 연결 실패: {str(err).splitlines()[0]}"
            if require_postgres:
                return [Verdict(case["name"], "(연결)", "FAIL", pg_note)]
    engines: dict[str, Any] = {"ours": Lrn(workdir), "sqlite": Sqlite()}
    if postgres is not None:
        engines["postgres"] = postgres
    verdicts: list[Verdict] = []
    try:
        for sql in case.get("setup", []):
            for name, engine in engines.items():
                try:
                    engine.run(sql)
                except EngineError as err:
                    verdicts.append(Verdict(case["name"], sql, "FAIL", f"setup이 {name}에서 실패: {err}"))
                    return verdicts
        for query in case["queries"]:
            query = query if isinstance(query, dict) else {"sql": query}
            results: dict[str, tuple[str, Any] | None] = {name: outcome_of(engine, query["sql"]) for name, engine in engines.items()}
            if "postgres" not in engines:
                results["postgres"] = None
            outcome, detail = judge(query, results)
            verdicts.append(Verdict(case["name"], query["sql"], outcome, detail or pg_note))
    finally:
        for engine in engines.values():
            engine.close()
    return verdicts


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dsn", default=os.environ.get("SQLDIFF_DSN", ""))
    parser.add_argument("--require-postgres", action="store_true")
    parser.add_argument("--only", default="")
    args = parser.parse_args()
    if args.require_postgres and not args.dsn:
        print("SQLDIFF_DSN이 없다", file=sys.stderr)
        return 2
    counts: dict[str, int] = {}
    with tempfile.TemporaryDirectory(prefix="sqldiff-") as tmp:
        for case in CASES:
            if args.only and args.only not in case["name"]:
                continue
            for verdict in run_case(case, Path(tmp), args.dsn or None, require_postgres=args.require_postgres):
                counts[verdict.outcome] = counts.get(verdict.outcome, 0) + 1
                if verdict.outcome != "PASS":
                    print(f"  {verdict.outcome} [{verdict.case}] {verdict.sql}\n      {verdict.detail}")
    print("판정: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())) + f" (postgres {'사용' if args.dsn else '미사용'})")
    return 0 if counts.get("FAIL", 0) == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
